import { chromium } from 'playwright'
const browser = await chromium.launch({ args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
page.on('console', m => { if (m.type() === 'error') console.log(`[err] ${m.text().slice(0, 200)}`) })
await page.goto('http://127.0.0.1:4173/english-app/words', { waitUntil: 'networkidle' })
await page.waitForTimeout(4000)
const cards = await page.locator('button').filter({ hasText: '☆' }).count()
const card2 = await page.locator('a[href^="/words/"]').count()
const card3 = await page.locator('a').filter({ hasText: '☆' }).count()
const card4 = await page.locator('.hover\\:bg-stone-100').count()
console.log('button ☆:', cards)
console.log('a /words/:', card2)
console.log('a ☆:', card3)
console.log('hover stone:', card4)
const all = await page.content()
console.log('empty msg:', all.includes('还没有') || all.includes('加载') || all.includes('empty'))
await browser.close()
